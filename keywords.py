# 평면 키워드 리스트(중복 제거, 순서 유지)
def _flatten():
    seen = set()
    out = []
    for kws in DISCLOSURE_MAP.values():
        for k in kws:
            if k not in seen:
                seen.add(k)
                out.append(k)
    return out

KEYWORDS = _flatten()

# 키워드 -> 공시분류 역매핑
KEYWORD_TO_CATEGORY = {}
for cat, kws in DISCLOSURE_MAP.items():
    for k in kws:
        KEYWORD_TO_CATEGORY.setdefault(k, cat)

def classify(keyword):
    return KEYWORD_TO_CATEGORY.get(keyword, "기타")
